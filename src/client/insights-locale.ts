export function insightsText(locale: string, key: string, params: Record<string, string | number> = {}): string {
  const dictionary = locale.toLowerCase().startsWith('zh') ? insightsZh : insightsEn;
  return (dictionary[key] ?? key).replace(/\{(\w+)\}/g, (token, name: string) => String(params[name] ?? token));
}
